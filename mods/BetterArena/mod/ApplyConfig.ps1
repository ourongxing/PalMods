param([string]$RewardMultiplier, [switch]$Prompt)
$ErrorActionPreference = 'Stop'
if (Get-Process 'Palworld-Win64-Shipping' -ErrorAction SilentlyContinue) {
    throw 'Close Palworld before applying Better Arena configuration.'
}
$modRoot = [IO.Path]::GetFullPath($PSScriptRoot)
$schemaRoot = Join-Path (Split-Path -Parent $modRoot) 'PalSchema'
if (-not (Test-Path -LiteralPath (Join-Path $schemaRoot 'dlls/main.dll'))) {
    throw 'PalSchema is required. Install PalSchema before applying Better Arena configuration.'
}
$configPath = Join-Path $modRoot 'Scripts/config.lua'
$configText = [IO.File]::ReadAllText($configPath)
if ($Prompt) { $RewardMultiplier = Read-Host 'Arena reward multiplier (integer 1-10; blank keeps current setting)' }
$changeConfig = -not [string]::IsNullOrWhiteSpace($RewardMultiplier)
if (-not $changeConfig) {
    $match = [regex]::Match($configText, '(?m)^\s*RewardMultiplier\s*=\s*([^,\r\n]+)')
    $RewardMultiplier = if ($match.Success) { $match.Groups[1].Value.Trim() } else { '2' }
}
if ($RewardMultiplier -notmatch '^(?:[1-9]|10)$') { throw 'RewardMultiplier must be an integer from 1 to 10.' }
$multiplier = [int]$RewardMultiplier
$table = Get-Content -LiteralPath (Join-Path $modRoot 'Config/arena_rewards.base.json') -Raw | ConvertFrom-Json
foreach ($rank in @('Bronze','Silver','Gold','Platinum','Diamond','Master','Legend')) {
    $row = $table.DT_ArenaSoloRewardTable.$rank
    if ($null -eq $row) { throw "Missing base reward rank: $rank" }
    foreach ($field in @('FirstClearReward','RepeatClearReward')) {
        foreach ($reward in $row.$field) {
            $reward.Min = [int]$reward.Min * $multiplier
            $reward.Max = [int]$reward.Max * $multiplier
        }
    }
}
$patchRoot = Join-Path $schemaRoot 'mods/BetterArena'
$rawPath = Join-Path $patchRoot 'raw/arena_rewards.json'
$pointsPath = Join-Path $patchRoot 'blueprints/arena_points.json'
$utf8 = New-Object System.Text.UTF8Encoding($false)
foreach ($path in @($rawPath,$pointsPath)) { New-Item -ItemType Directory -Path (Split-Path -Parent $path) -Force | Out-Null }
$points = @{ BP_PalGameSetting_C = @{ Arena_RankPoint_WinToNPC = 50 * $multiplier } }
[IO.File]::WriteAllText($rawPath, ($table | ConvertTo-Json -Depth 12) + [Environment]::NewLine, $utf8)
[IO.File]::WriteAllText($pointsPath, ($points | ConvertTo-Json -Depth 4) + [Environment]::NewLine, $utf8)
if ($changeConfig) {
    if ($configText -match '(?m)^\s*RewardMultiplier\s*=') {
        $configText = [regex]::Replace($configText, '(?m)^(\s*RewardMultiplier\s*=)[^,\r\n]+', { param($m) $m.Groups[1].Value + $multiplier })
    } else {
        $configText = [regex]::Replace($configText, 'return\s*\{', "return {`r`n    RewardMultiplier = $multiplier,", 1)
    }
    [IO.File]::WriteAllText($configPath, $configText, $utf8)
}
[IO.File]::WriteAllText((Join-Path $modRoot 'Scripts/applied_multiplier.lua'), "-- Generated by ApplyConfig.ps1.`nreturn $multiplier`n", $utf8)
Write-Output "Applied Better Arena x$multiplier to all NPC first-clear/repeat rewards and victory base RP. Restart Palworld."
